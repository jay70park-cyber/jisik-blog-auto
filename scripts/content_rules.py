def build_council_section(rows):
    """council_minutes.csv 에서 읽은 행들을 프롬프트용 문자열로 만든다.

    rows 는 dict 목록. 요약이 비어 있거나 '없음'인 것은 뺀다.
    쓸 내용이 없으면 빈 문자열을 돌려주므로,
    호출하는 쪽에서 그대로 프롬프트에 더하면 된다.
    """
    lines = []
    for r in rows:
        summary = (r.get("요약") or "").strip()
        if not summary or summary == "없음":
            continue
        lines.append("- {} {} : {}".format(
            r.get("회의일", ""), r.get("회의명", ""), summary))
        # 링크를 넘기지 않으면 모델이 근거를 달 방법이 없다.
        # 지어내는 것은 금지되어 있으므로 결과적으로 링크 없는 글이 나온다.
        link = (r.get("링크") or "").strip()
        if link:
            lines.append("    근거 링크: " + link)
