def build_rules(category="jisik"):
    """카테고리에 맞는 해시태그를 끼워 넣은 규칙 문자열을 돌려준다."""
    tags = HASHTAGS.get(category, HASHTAGS["jisik"])
    return CONTENT_RULES.format(hashtags=tags)


