COUNCIL_SECTION_RULE = """
[시의회에서 나온 이야기 — 이 섹션을 포함할 것]
아래는 최근 화성특례시의회 회의록에서 뽑은 내용이다.
이 중 이 글의 주제와 닿는 것을 골라 한 섹션으로 쓸 것.

- 회의록은 공식 보도자료에 없는 내용이 나오는 자리다.
  유찰 횟수, 증액 사유, 일정이 밀린 까닭 같은 것이 여기서 드러난다.
  그 점을 독자에게 알려줄 것: 이건 기사에 안 나온 이야기다
- 발언은 요약해서 전하고 그대로 길게 옮기지 말 것
- 숫자는 회의록에 적힌 그대로 쓰되, 회의록 특성상 발언자의
  착오가 섞일 수 있으므로 단정하지 말 것
- 회의 날짜와 위원회 이름을 함께 밝힐 것
  (예: "9월 3일 도시건설위원회에서는")
- 주제와 닿는 내용이 없으면 이 섹션을 생략할 것. 억지로 끼워 넣지 말 것

회의록 요약:
{council}
"""


def build_council_section(rows):
    """council_minutes.csv 에서 읽은 행들을 프롬프트용 문자열로 만든다.

    rows 는 dict 목록. 요약이 비어 있거나 '없음'인 것은 뺀다.
    쓸 내용이 없으면 빈 문자열을 돌려주므로,
    호출하는 쪽에서 그대로 프롬프트에 더하면 된다.
    """
    lines = []
    for r in rows:
        summary = (r.get("요약") or "").strip()
        if not summary or summary == "없음":
            continue
        lines.append("- {} {} : {}".format(
            r.get("회의일", ""), r.get("회의명", ""), summary))
    if not lines:
        return ""
    return COUNCIL_SECTION_RULE.format(council="\n".join(lines[:8]))


