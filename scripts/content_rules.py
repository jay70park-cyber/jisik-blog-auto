def pick_theme(today=None):
    """오늘 날짜에 맞는 (카테고리키, 표시명, 세부주제) 를 돌려준다.

    세부주제가 None 이면 호출하는 쪽에서 정한다.
    - jisik  : 기존 6개 분류 순환 로직을 그대로 쓴다
    - local  : 매주 검색으로 발굴한다 (고정 목록은 금방 소진되고 시의성이 떨어짐)
    """
    if today is None:
        today = datetime.date.today()

    # 월요일(0)
    if today.weekday() == 0:
        return "jisik", "지식산업센터", None

    # 목요일(3) - ISO 주차 홀짝으로 교차
    week = today.isocalendar()[1]
    if week % 2 == 1:
        idx = (week // 2) % len(SANGGA_CATEGORIES)
        return "sangga", "상가·공장", SANGGA_CATEGORIES[idx]

    return "local", "동탄 지역 개발 이슈", None


